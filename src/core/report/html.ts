function renderCards(result: RunResult): string {
  const totals = result.totals;
  const latencies = result.cases.flatMap((c) => c.attempts.map((a) => a.latencyMs));
  const sorted = [...latencies].sort((a, b) => a - b);
  const p50 = percentile(sorted, 50);
  const p95 = percentile(sorted, 95);

  return [
    card('Cases', String(totals.cases)),
    card('Passed', String(totals.passed), 'ok'),
    card('Failed', String(totals.failed), totals.failed > 0 ? 'bad' : undefined),
    card('Flaky', String(totals.flaky), totals.flaky > 0 ? 'warn' : undefined),
    card('Skipped', String(totals.skipped)),
    card('Pass rate', `${(totals.passRate * 100).toFixed(1)}%`),
    card('Latency p50', `${Math.round(p50)} ms`),
    card('Latency p95', `${Math.round(p95)} ms`),
    card('Requests', String(totals.requests)),
    card('Duration', `${(result.meta.durationMs / 1000).toFixed(2)} s`),
  ].join('\n    ');
}

function card(label: string, value: string, tone?: 'ok' | 'bad' | 'warn'): string {
  return `<div class="card${tone ? ` card-${tone}` : ''}"><span class="card-label">${escapeHtml(label)}</span><span class="card-value">${escapeHtml(value)}</span></div>`;
}

function renderComparison(comparison: NonNullable<RunResult['comparison']>): string {
  const rows: string[] = [];
  for (const delta of comparison.regressions) {
    rows.push(`<li class="bad">✗ ${escapeHtml(delta.id)} — ${escapeHtml(delta.a)} → ${escapeHtml(delta.b)} (${escapeHtml(delta.failingChecks.join(', ') || 'no failing check recorded')})</li>`);
  }
  for (const delta of comparison.fixes) {
    rows.push(`<li class="ok">✔ ${escapeHtml(delta.id)} — ${escapeHtml(delta.a)} → ${escapeHtml(delta.b)}</li>`);
  }
  for (const violation of comparison.violations) {
    rows.push(`<li class="bad">⚠ threshold ${escapeHtml(violation.metric)}: ${escapeHtml(violation.message)}</li>`);
  }

  const checkRows = comparison.checkTypeDeltas
    .map(
      (delta) =>
        `<tr><td>${escapeHtml(delta.type)}</td><td>${(delta.aPassRate * 100).toFixed(1)}%</td><td>${(delta.bPassRate * 100).toFixed(1)}%</td><td class="${delta.delta < 0 ? 'bad' : 'ok'}">${delta.delta >= 0 ? '+' : ''}${(delta.delta * 100).toFixed(1)}pp</td></tr>`,
    )
    .join('\n');

  const drift = comparison.similarityDrift
    .filter((entry) => Math.abs(entry.delta) >= 0.01)
    .map(
      (entry) =>
        `<tr><td>${escapeHtml(entry.id)}</td><td>${entry.a.toFixed(3)}</td><td>${entry.b.toFixed(3)}</td><td class="${entry.delta < 0 ? 'bad' : 'ok'}">${entry.delta >= 0 ? '+' : ''}${entry.delta.toFixed(3)}</td></tr>`,
    )
    .join('\n');

  return `
    <div class="compare-grid">
      <div>
        <h3>Regressions &amp; fixes</h3>
        ${rows.length ? `<ul class="diff-list">${rows.join('')}</ul>` : '<p class="muted">No case flipped status.</p>'}
        <p class="muted">Pass rate delta: <strong>${comparison.passRateDelta >= 0 ? '+' : ''}${(comparison.passRateDelta * 100).toFixed(2)}pp</strong>
        · latency p95 ${comparison.latency.p95DeltaPct >= 0 ? '+' : ''}${comparison.latency.p95DeltaPct.toFixed(1)}%</p>
      </div>
      <div>
        <h3>Per check type</h3>
        <table class="mini"><thead><tr><th>Type</th><th>Before</th><th>After</th><th>Δ</th></tr></thead><tbody>
        ${checkRows}
        </tbody></table>
      </div>
      <div>
        <h3>Similarity drift</h3>
        ${
          drift
            ? `<table class="mini"><thead><tr><th>Case</th><th>Before</th><th>After</th><th>Δ</th></tr></thead><tbody>
        ${drift}
        </tbody></table>`
            : '<p class="muted">No similarity drift above 0.01.</p>'
        }
      </div>
    </div>`;
}

function renderRow(caseResult: CaseResult, result: RunResult, baseline?: RunResult): string {
  const checksPassed = caseResult.checks.reduce((sum, c) => sum + c.passCount, 0);
  const checksTotal = caseResult.checks.reduce((sum, c) => sum + c.total, 0);
  const ttft = caseResult.ttftMs ?? 0;
  const status = caseResult.status;

  const detail = renderDetail(caseResult, result, baseline);

  return `      <tr class="case-row" data-status="${status}" data-name="${escapeAttr(caseResult.id)}" data-passrate="${caseResult.passRate}" data-checks="${checksTotal - checksPassed}" data-p50="${caseResult.latencyMs.p50}" data-p95="${caseResult.latencyMs.p95}" data-ttft="${ttft}" data-duration="${caseResult.durationMs}">
        <td class="col-toggle"><button class="toggle" type="button" aria-expanded="false">▸</button></td>
        <td class="col-name">${escapeHtml(caseResult.id)}${caseResult.tags?.length ? `<span class="tags">${caseResult.tags.map((t) => `<span class="tag">${escapeHtml(t)}</span>`).join('')}</span>` : ''}</td>
        <td><span class="badge badge-${status}">${escapeHtml(status)}</span></td>
        <td class="num">${(caseResult.passRate * 100).toFixed(0)}%</td>
        <td class="num">${checksPassed}/${checksTotal}</td>
        <td class="num">${Math.round(caseResult.latencyMs.p50)} ms</td>
        <td class="num">${Math.round(caseResult.latencyMs.p95)} ms</td>
        <td class="num">${ttft ? `${Math.round(ttft)} ms` : '—'}</td>
        <td class="num">${Math.round(caseResult.durationMs)} ms</td>
      </tr>
      <tr class="detail-row" hidden><td colspan="9">${detail}</td></tr>`;
}

function renderDetail(caseResult: CaseResult, result: RunResult, baseline?: RunResult): string {
  const checkRows = caseResult.checks
    .map(
      (check) =>
        `<tr><td><code>${escapeHtml(check.id)}</code></td><td>${escapeHtml(check.type)}</td><td>${check.passCount}/${check.total}</td><td>${
          check.scores.length
            ? check.scores.map((s) => s.toFixed(3)).join(', ')
            : '—'
        }</td><td>${check.reasons.map((r) => escapeHtml(r)).join('<br>') || '—'}</td></tr>`,
    )
    .join('\n');

  const baselineCase = baseline?.cases.find((c) => c.id === caseResult.id);
  const diff = buildDiffHtml(baselineCase, caseResult);

  return `<div class="detail">
  <div class="detail-grid">
    <div>
      <h4>Checks</h4>
      <table class="mini"><thead><tr><th>Check</th><th>Type</th><th>Passed</th><th>Scores</th><th>Reasons</th></tr></thead><tbody>
      ${checkRows}
      </tbody></table>
    </div>
    <div>
      <h4>Response diff</h4>
      <p class="muted">${diff.caption}</p>
      <pre class="diff">${diff.html}</pre>
    </div>
  </div>
  ${renderAttempts(caseResult)}
</div>`;
}

function renderAttempts(caseResult: CaseResult): string {
  if (caseResult.attempts.length === 0) return '';
  const blocks = caseResult.attempts
    .map(
      (attempt) => `<details class="attempt">
  <summary>Attempt ${attempt.index + 1} · status ${attempt.status ?? 'n/a'} · ${Math.round(attempt.latencyMs)}ms${
    attempt.ttftMs !== undefined ? ` · ttft ${Math.round(attempt.ttftMs)}ms` : ''
  }${attempt.error ? ` · <span class="bad">${escapeHtml(attempt.error)}</span>` : ''}</summary>
${attempt.turns ? renderTurns(attempt.turns) : `  <pre class="request">${escapeHtml(formatRequest(attempt))}</pre>
  <pre class="response">${escapeHtml(attempt.text || '(empty response)')}</pre>`}
</details>`,
    )
    .join('\n');
  return `<div class="attempts">${blocks}</div>`;
}

function renderTurns(turns: TurnResult[]): string {
  return turns
    .map(
      (turn) => `  <p class="muted">Turn ${turn.index + 1} · status ${turn.status ?? 'n/a'} · ${Math.round(turn.latencyMs)}ms${
        turn.error ? ` · <span class="bad">${escapeHtml(turn.error)}</span>` : ''
      }</p>
  <pre class="request">${escapeHtml(turn.input)}</pre>
  <pre class="response">${escapeHtml(turn.text || '(empty response)')}</pre>`,
    )
    .join('\n');
}

function formatRequest(attempt: CaseResult['attempts'][number]): string {
  const body =
    attempt.request.body === undefined
      ? ''
      : `\n\n${typeof attempt.request.body === 'string' ? attempt.request.body : JSON.stringify(attempt.request.body, null, 2)}`;
  return `${attempt.request.method} ${attempt.request.url}\n${Object.entries(attempt.request.headers)
    .map(([k, v]) => `${k}: ${v}`)
    .join('\n')}${body}`;
}

export interface DiffHtml {
  html: string;
  caption: string;
}

export function buildDiffHtml(baseline: CaseResult | undefined, current: CaseResult): DiffHtml {
  const currentText = current.attempts[0]?.text ?? '';
  const currentLines = currentText.split('\n');

  if (baseline) {
    const baselineText = baseline.attempts[0]?.text ?? '';
    const diff = diffLines(baselineText.split('\n'), currentLines);
    return {
      html: renderDiff(diff),
      caption: `Baseline (${baseline.status}) vs. current (${current.status})`,
    };
  }

  if (current.attempts.length > 1) {
    const first = current.attempts[0]!.text.split('\n');
    const last = current.attempts[current.attempts.length - 1]!.text.split('\n');
    return {
      html: renderDiff(diffLines(first, last)),
      caption: 'Attempt 1 vs. last attempt (repeat consistency)',
    };
  }

  return {
    html: `<span class="muted">single attempt - response shown below</span>\n${escapeHtml(currentText)}`,
    caption: 'Response',
  };
}

type DiffOp = { kind: 'same' | 'add' | 'del'; text: string };

export function diffLines(a: string[], b: string[]): DiffOp[] {
  const n = a.length;
  const m = b.length;
  const table: number[][] = Array.from({ length: n + 1 }, () => new Array<number>(m + 1).fill(0));
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      const row = table[i]!;
      const nextRow = table[i + 1]!;
      row[j] = a[i] === b[j] ? nextRow[j + 1]! + 1 : Math.max(nextRow[j]!, row[j + 1]!);
    }
  }
  const ops: DiffOp[] = [];
  let i = 0;
  let j = 0;
  while (i < n && j < m) {
    if (a[i] === b[j]) {
      ops.push({ kind: 'same', text: a[i]! });
      i++;
      j++;
    } else if (table[i + 1]![j]! >= table[i]![j + 1]!) {
      ops.push({ kind: 'del', text: a[i]! });
      i++;
    } else {
      ops.push({ kind: 'add', text: b[j]! });
      j++;
    }
  }
  while (i < n) {
    ops.push({ kind: 'del', text: a[i]! });
    i++;
  }
  while (j < m) {
    ops.push({ kind: 'add', text: b[j]! });
    j++;
  }
  return ops;
}

function renderDiff(ops: DiffOp[]): string {
  if (ops.length === 0) return '<span class="muted">(empty)</span>';
  return ops
    .map((op) => {
      const prefix = op.kind === 'add' ? '+' : op.kind === 'del' ? '-' : ' ';
      return `<span class="diff-${op.kind}">${prefix} ${escapeHtml(op.text)}</span>`;
    })
    .join('\n');
}

function percentile(sorted: number[], p: number): number {
  if (sorted.length === 0) return 0;
  if (sorted.length === 1) return sorted[0]!;
  const rank = (p / 100) * (sorted.length - 1);
  const low = Math.floor(rank);
  const high = Math.ceil(rank);
  if (low === high) return sorted[low]!;
  return sorted[low]! * (1 - (rank - low)) + sorted[high]! * (rank - low);
}

export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function escapeAttr(value: string): string {
  return escapeHtml(value);
}

